using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace FunctionalLint.Heal;

/// <summary>
/// The strict checks heal runs when a <see cref="Policy"/> governs the project: everything that switches FunctionalLint
/// off, reported as FP0016. They run here, outside the build, because the build's own settings are what they check.
/// </summary>
public static class Gate
{
    private static DiagnosticDescriptor Rule => FunctionalAnalyzer.RuleSwitchedOff;

    private static readonly ImmutableArray<string> RuleIds =
        [.. new FunctionalAnalyzer().SupportedDiagnostics.Select(d => d.Id)];

    // The .NET culture rules FunctionalCore.props turns on as errors.
    private static readonly ImmutableArray<string> CultureRules = ["CA1304", "CA1305", "CA1309", "CA1310", "CA1311"];

    // Compiler warnings FunctionalCore.props makes errors: non-exhaustive switches, and every nullable warning (the
    // compiler's own list, as '/nowarn:nullable' expands it).
    private const string NonExhaustiveSwitch = "CS8509";

    private static readonly ImmutableHashSet<string> NullableWarnings = CSharpCommandLineParser.Default
        .Parse(["/nowarn:nullable"], Environment.CurrentDirectory, sdkDirectory: null)
        .CompilationOptions.SpecificDiagnosticOptions.Keys.ToImmutableHashSet(StringComparer.OrdinalIgnoreCase);

    // MSBuild settings that stop the build running analyzers at all.
    private static readonly string[] AnalyzerSwitches = ["RunAnalyzers", "RunAnalyzersDuringBuild"];

    public static IEnumerable<Diagnostic> Check(Project project, Compilation compilation, Policy policy, CancellationToken ct)
    {
        // The project's own files: not obj/ (GlobalUsings.g.cs and friends), not source generators' output.
        var own = project.Documents.Select(d => d.FilePath).OfType<string>()
            .Where(path => !InObjFolder(project, path)).ToHashSet(StringComparer.Ordinal);
        var sources = compilation.SyntaxTrees.Where(t => own.Contains(t.FilePath)).ToList();
        bool May(string id) => policy.MayLower.Contains(id, StringComparer.OrdinalIgnoreCase);

        // Pragmas and [SuppressMessage], scanned here too: in the build a pragma can switch FP0016 itself off. Then
        // [GeneratedCode] and '#line hidden', which the build can't report: every analyzer skips the code they mark.
        foreach (var tree in sources)
        {
            var model = compilation.GetSemanticModel(tree);
            foreach (var found in FunctionalAnalyzer.SwitchOffs(tree, model, policy.MayLower, ct).Concat(FunctionalAnalyzer.HiddenFromAnalyzers(tree, model, ct)))
                yield return found;
        }

        foreach (var tree in sources)
            if (GeneratedMarker(tree, project.AnalyzerOptions.AnalyzerConfigOptionsProvider.GetOptions(tree)))
                yield return Diagnostic.Create(Rule, Location.Create(tree, default), Path.GetFileName(tree.FilePath),
                    "is skipped as generated code", "Remove the marker (<auto-generated> header, .g.cs name or generated_code).");

        var lowered = Lowered(project, compilation, sources, ct)
            .Where(l => !May(l.Id) && !(NullableWarnings.Contains(l.Id) && May("nullable")))
            .ToList();
        // Nullable warnings come as a group ('<NoWarn>nullable</NoWarn>' lowers dozens), so they're reported together.
        foreach (var group in lowered.GroupBy(l => (Nullable: NullableWarnings.Contains(l.Id), l.Level)))
            foreach (var id in group.Key.Nullable ? [Summary(group.Select(l => l.Id))] : group.Select(l => l.Id))
                yield return Diagnostic.Create(Rule, Location.None, id,
                    $"is lowered to '{group.Key.Level}' in '{project.Name}' (NoWarn, .editorconfig or .globalconfig)", "Remove that setting.");

        foreach (var id in NotErrors(compilation, sources, ct).Where(id => !May(id)))
            yield return Diagnostic.Create(Rule, Location.None, id,
                $"isn't an error in '{project.Name}'", "Restore TreatWarningsAsErrors and the WarningsAsErrors that FunctionalCore.props sets.");

        if (compilation.Options.NullableContextOptions != NullableContextOptions.Enable && !May("nullable"))
            yield return Diagnostic.Create(Rule, Location.None, project.Name,
                "has nullable checking turned off", "Remove the <Nullable> setting that turns it off.");

        if (project.FilePath is { } projectFile)
        {
            foreach (var (file, line, name, value) in AnalyzersSwitchedOff(projectFile))
                yield return Diagnostic.Create(Rule, FileLocation(file, line), name,
                    $"is '{value}' for '{project.Name}', so its build runs no analyzers", "Remove that setting.");

            foreach (var nested in policy.PoliciesBelowRoot(projectFile))
                yield return Diagnostic.Create(Rule, FileLocation(nested, 0),
                    Path.GetRelativePath(policy.Root, nested).Replace('\\', '/'),
                    $"would replace the root policy for '{project.Name}' in the build", "Remove it, and change the root policy instead.");
        }
    }

    // 'CS8600', or 'CS8600, CS8601, CS8602 and 60 more'.
    private static string Summary(IEnumerable<string> ids)
    {
        var sorted = ids.Order(StringComparer.Ordinal).ToList();
        var shown = string.Join(", ", sorted.Take(3));
        return sorted.Count > 3 ? $"{shown} and {sorted.Count - 3} more" : shown;
    }

    private static Location FileLocation(string file, int line) =>
        Location.Create(file, default, new Microsoft.CodeAnalysis.Text.LinePositionSpan(new(line, 0), new(line, 0)));

    /// <summary>A policy core that doesn't load FunctionalLint: its build checks nothing.</summary>
    public static Diagnostic MissingAnalyzer(Project project) =>
        Diagnostic.Create(Rule, Location.None, project.Name,
            "is a policy core but doesn't load FunctionalLint", "Restore its import of FunctionalCore.props.");

    private static bool InObjFolder(Project project, string path) =>
        project.FilePath is { } file
        && Path.GetRelativePath(Path.Combine(Path.GetDirectoryName(file)!, "obj"), path) is var relative
        && !relative.StartsWith("..", StringComparison.Ordinal) && !Path.IsPathRooted(relative);

    // Each rule set below 'error', and where: compiler options (NoWarn, ruleset), then .editorconfig/.globalconfig
    // settings for the whole project or for files, then bulk settings for the category or every analyzer. FunctionalLint's
    // rules, the culture rules, CS8509 and the nullable warnings.
    private static IEnumerable<(string Id, string Level)> Lowered(Project project, Compilation compilation, List<SyntaxTree> sources, CancellationToken ct)
    {
        // Compiler warnings are only errors because the props file raises them, so 'default' lowers them too.
        static bool IsLowered(string id, ReportDiagnostic value) =>
            value is not (ReportDiagnostic.Error or ReportDiagnostic.Default) || (value == ReportDiagnostic.Default && IsCompilerWarning(id));
        static string Name(ReportDiagnostic value) => value switch
        {
            ReportDiagnostic.Warn or ReportDiagnostic.Default => "warning",
            ReportDiagnostic.Info => "suggestion",
            ReportDiagnostic.Hidden => "silent",
            ReportDiagnostic.Suppress => "none",
            _ => value.ToString().ToLowerInvariant(),
        };

        var found = new Dictionary<string, string>(StringComparer.Ordinal);
        var specific = compilation.Options.SpecificDiagnosticOptions;
        var trees = compilation.Options.SyntaxTreeOptionsProvider;
        foreach (var id in RuleIds.Concat(CultureRules).Append(NonExhaustiveSwitch).Concat(NullableWarnings.Order(StringComparer.Ordinal)))
        {
            if (specific.TryGetValue(id, out var value) && IsLowered(id, value)) found.TryAdd(id, Name(value));
            if (trees is null) continue;
            if (trees.TryGetGlobalDiagnosticValue(id, ct, out var global) && IsLowered(id, global)) found.TryAdd(id, Name(global));
            foreach (var tree in sources)
                if (trees.TryGetDiagnosticValue(tree, id, ct, out var local) && IsLowered(id, local)) found.TryAdd(id, Name(local));
        }

        var config = project.AnalyzerOptions.AnalyzerConfigOptionsProvider;
        foreach (var options in sources.Select(config.GetOptions).Prepend(config.GlobalOptions))
            foreach (var key in new[] { "dotnet_analyzer_diagnostic.category-functional.severity", "dotnet_analyzer_diagnostic.severity" })
                if (options.TryGetValue(key, out var level) && level.Trim().ToLowerInvariant() is not ("error" or "default"))
                    found.TryAdd(key.Contains("category") ? "category Functional" : "every analyzer", level.Trim());

        return found.Select(kv => (kv.Key, kv.Value));
    }

    private static bool IsCompilerWarning(string id) => id == NonExhaustiveSwitch || NullableWarnings.Contains(id);

    // CS8509 and the nullable warnings when nothing makes them errors: TreatWarningsAsErrors and the props file's
    // WarningsAsErrors were both taken away. (A setting that lowers one is reported by Lowered.) Nullable as one finding.
    private static IEnumerable<string> NotErrors(Compilation compilation, List<SyntaxTree> sources, CancellationToken ct)
    {
        if (compilation.Options.GeneralDiagnosticOption == ReportDiagnostic.Error) return [];
        var trees = compilation.Options.SyntaxTreeOptionsProvider;
        bool Raised(string id) =>
            compilation.Options.SpecificDiagnosticOptions.ContainsKey(id)
            || (trees is not null && (trees.TryGetGlobalDiagnosticValue(id, ct, out _) || sources.Any(t => trees.TryGetDiagnosticValue(t, id, ct, out _))));
        var switches = Raised(NonExhaustiveSwitch) ? [] : new[] { NonExhaustiveSwitch };
        var nullable = compilation.Options.NullableContextOptions == NullableContextOptions.Enable && NullableWarnings.Any(id => !Raised(id))
            ? new[] { "nullable" } : [];
        return switches.Concat(nullable);
    }

    // <RunAnalyzers> or <RunAnalyzersDuringBuild> set to anything but true, in the project file or an MSBuild file it
    // reads (Directory.Build.*, imports). A core has no reason to set them, so a value we can't read counts too.
    private static IEnumerable<(string File, int Line, string Name, string Value)> AnalyzersSwitchedOff(string projectFile) =>
        Server.MsBuildInputs(projectFile).Prepend(projectFile).Distinct(StringComparer.Ordinal).Where(File.Exists)
            .SelectMany(file =>
            {
                try
                {
                    return System.Xml.Linq.XDocument.Load(file, System.Xml.Linq.LoadOptions.SetLineInfo).Descendants()
                        .Where(e => AnalyzerSwitches.Contains(e.Name.LocalName, StringComparer.OrdinalIgnoreCase)
                                 && e.Parent?.Name.LocalName == "PropertyGroup"
                                 && !e.Value.Trim().Equals("true", StringComparison.OrdinalIgnoreCase))
                        .Select(e => (file, ((System.Xml.IXmlLineInfo)e).LineNumber - 1, e.Name.LocalName, e.Value.Trim()))
                        .ToList();
                }
                catch (Exception e) when (e is System.Xml.XmlException or IOException or UnauthorizedAccessException)
                {
                    return [];
                }
            });

    // How Roslyn decides a file is generated (and so skips it): a name like X.g.cs or X.designer.cs, an
    // <auto-generated> comment at the top, or generated_code = true in config.
    private static bool GeneratedMarker(SyntaxTree tree, AnalyzerConfigOptions options)
    {
        if (options.TryGetValue("generated_code", out var flag) && flag.Trim().Equals("true", StringComparison.OrdinalIgnoreCase)) return true;

        var name = Path.GetFileName(tree.FilePath);
        if (name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)) return true;
        var stem = Path.GetFileNameWithoutExtension(name);
        if (new[] { ".designer", ".generated", ".g", ".g.i" }.Any(s => stem.EndsWith(s, StringComparison.OrdinalIgnoreCase))) return true;

        return tree.GetRoot().GetLeadingTrivia()
            .Where(t => t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia))
            .Any(t => t.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)
                   || t.ToString().Contains("<autogenerated", StringComparison.OrdinalIgnoreCase));
    }
}
